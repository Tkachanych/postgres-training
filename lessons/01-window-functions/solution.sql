with cte as (
  select t.account_id
       , t.tx_dt
       , sum(amount) as day_net
  --     , *
    from transactions as t
  where t.status = 'posted'
  group by t.account_id, t.tx_dt
) select account_id
       , tx_dt 
       , day_net
       , sum(day_net) over (partition by account_id order by tx_dt rows between unbounded preceding and current row ) as running_balance
       , lag(day_net) over (partition by account_id order by tx_dt) as prev_day_net
       , dense_rank() over (partition by account_id order by day_net desc) as day_dense_rank
       , row_number() over(partition by account_id order by day_net desc, tx_dt) = 1 as is_best_day
    from cte
   order by account_id,tx_dt
;



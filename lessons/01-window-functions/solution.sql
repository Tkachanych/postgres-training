   накапливать суммы по транзакциям, а не по дням. Поэтому нужен двухуровневый
   запрос: CTE/подзапрос с агрегацией до дня, затем оконные функции поверх него.

3. Как PostgreSQL выполняет OVER (PARTITION BY ... ORDER BY ...): какие
   сортировки и проходы по данным он делает и почему предварительная агрегация
   до оконных функций важна для производительности?

   Окна вычисляются узлом WindowAgg. Ему нужен вход, отсортированный сначала по
   ключам PARTITION BY, затем по ключам ORDER BY. Если данные уже отсортированы
   (например, индексом или предыдущим Sort), PostgreSQL переиспользует порядок;
   иначе вставляет Sort (в PG 13+ возможен Incremental Sort при частичной
   упорядоченности).

   WindowAgg идёт по строкам в этом порядке, отслеживает границы партиций и
   поддерживает состояние рамки:
   - для UNBOUNDED PRECEDING агрегат накапливается инкрементально;
   - для ограниченных рамок буферизуется нужное окно строк;
   - ROW_NUMBER инкрементит счётчик, RANK/DENSE_RANK отслеживают peer-группы,
     LAG/LEAD держат небольшой буфер.

   Несколько оконных функций с одинаковыми PARTITION BY/ORDER BY считаются за один
   проход WindowAgg; разные спецификации могут потребовать отдельного Sort и
   отдельного WindowAgg.

   Почему предварительная агрегация важна: она уменьшает число строк до
   сортировки и оконного прохода (миллионы транзакций -> тысячи «счёт-дней»).
   Это снижает стоимость Sort, объём памяти и риск spill на диск, а также даёт
   правильную гранулярность (одна строка на день). Для диагностики смотреть
   EXPLAIN (ANALYZE, BUFFERS) — узлы Sort и WindowAgg. Индексы в помощь:
   (account_id, tx_dt) под порядок, либо (status, account_id, tx_dt) /

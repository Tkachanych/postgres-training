2. Почему day_net и running_balance нельзя корректно посчитать одним и тем же
   оконным вызовом в одном шаге без предварительной агрегации?

   Логический порядок: FROM -> WHERE -> GROUP BY -> HAVING -> оконные функции ->
   SELECT -> DISTINCT -> ORDER BY -> LIMIT. Окна считаются уже по строкам,
   полученным после группировки.

   day_net — это агрегат (SUM по дню), он появляется только после GROUP BY.
   running_balance — это окно уже над агрегированным day_net.

   Оконные функции нельзя вкладывать друг в друга: результат одного окна нельзя
   использовать как аргумент другого окна в том же уровне запроса.

   Без предварительной агрегации окно идёт по отдельным транзакциям: получится
